import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { validate } from '../kit/model.mjs';
import { renderPage, renderMap } from '../kit/render.mjs';

const fixture = new URL('../examples/heat-exposure/', import.meta.url);
const issue = JSON.parse(await readFile(new URL('issue.json', fixture), 'utf8'));
const scene = JSON.parse(await readFile(new URL('scene.json', fixture), 'utf8'));
assert.equal(validate(issue, scene), true);
assert(issue.entities.every(e => e.kind === 'place'), 'The transfer map must not turn environmental places into IT services');
assert(scene.instances.every(a => !['cabinet','server','database','gateway','workshop'].includes(a.asset)));
const byId = new Map(issue.relationships.map(r => [r.id, r]));
const walk = issue.scenarios[0].steps.flatMap(s => s.relations.map(id => byId.get(id)).filter(r => r.kind === 'movement'));
assert.deepEqual(walk.map(r => r.from).concat(walk.at(-1).to), ['home','school','square','park','cool-room']);
assert(walk.every((r,i) => i === 0 || walk[i-1].to === r.from), 'The ordinary journey must have no missing handoff');
const exception = issue.scenarios.find(s => s.id === 'closed-door');
const returnLeg = byId.get(exception.steps.at(-1).relations[0]);
assert.equal(returnLeg.from, 'cool-room');
assert.equal(returnLeg.to, 'park');
assert(exception.steps[1].problem && exception.steps[1].relations.includes('room-access'));
assert(exception.outcome.includes('without reaching indoor refuge'), 'The exception must not claim successful indoor access');
const influence = byId.get('paving-influence');
assert.equal(influence.kind, 'influence');
assert.equal(influence.status, 'inferred', 'An application of a general mechanism is not a measured local fact');
assert.equal(influence.source, 'epa-surfaces');
assert(issue.sources.some(s => s.id === 'epa-trees') && issue.sources.some(s => s.id === 'who-heat'));
assert(scene.scenarioLayouts.every(layout => layout.steps.length === issue.scenarios.find(s => s.id === layout.scenario).steps.length));

const svg = renderMap(issue, scene);
assert.equal(svg, renderMap(issue, scene));
assert(!/\b(?:NaN|Infinity|undefined)\b/.test(svg));
assert.equal((svg.match(/class="map-object /g) ?? []).length, issue.entities.length);
assert.equal((svg.match(/data-story-step=/g) ?? []).length, 7);
const html = renderPage(issue, scene, '', '');
assert(!/Northbank|repair|booking/i.test(html), 'The transfer output must not inherit the repair narrative');
assert(!html.includes('0 services') && !html.includes('0 technical groups'));
const legend = html.match(/<div class="legend"[^>]*>(.*?)<\/div>/s)[1];
assert(legend.includes('Environmental influence') && !legend.includes('Technical links'));
for (const source of issue.sources) assert(html.includes(source.title));
const published = html.split('<script type="application/json" id="map-data">')[0];
assert(!/fictional|Evidence:|Issue status:|not a measured|does not calculate/i.test(published), 'Published copy explains the story without disclaimer boilerplate');
assert(html.includes('"status":"inferred"'), 'Source status stays in internal data');
const unsupported = structuredClone(issue);
unsupported.relationships[0].kind = 'temperature';
assert.throws(() => validate(unsupported, scene), /Unknown relationship kind/);
console.log('Passed: non-IT heat example, continuous resident journey, unresolved closed-door outcome, qualified environmental influence, both local story layouts, deterministic assets and domain-neutral page copy.');
